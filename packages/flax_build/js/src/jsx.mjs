import {
  existsSync,
  readFileSync,
  writeFileSync,
  renameSync,
  rmSync,
  lstatSync,
} from 'node:fs';
import MagicString, { Bundle } from 'magic-string';
import { dirname, relative, resolve, isAbsolute, sep } from 'node:path';
import { API, SignatureKind, SymbolFlags, TypeFlags } from 'typescript/unstable/sync';
import { SyntaxKind } from 'typescript/unstable/ast';
import { EntityDecoder, ALL_ENTITIES } from '@nodable/entities';

const entities = new EntityDecoder({ namedEntities: ALL_ENTITIES });

const marker = '// Generated by @flax/build JSX v1. Do not edit.\n';
const header = `${marker}import type { Widget, StatelessWidget, StatefulWidget } from '@flax/flutter/widgets';\ntype FlaxJsxWidget = Widget;\ntype FlaxJsxWidgets = Widget[];\ntype FlaxJsxStateless = StatelessWidget;\ntype FlaxJsxStateful = StatefulWidget;\n`;

/** Read only the owning application's switch, never an imported dependency's flag. */
export function jsxEnabled(root) {
  const file = resolve(root, 'package.json');
  if (!existsSync(file)) return false;
  const value = JSON.parse(readFileSync(file, 'utf8')).flax?.jsx;
  if (value !== undefined && typeof value !== 'boolean')
    throw new Error(`${file}: flax.jsx must be a boolean`);
  return value === true;
}

function publish(file, contents) {
  const previous = lstatSync(file, { throwIfNoEntry: false });
  if (previous) {
    if (!previous.isFile() || !readFileSync(file, 'utf8').startsWith(marker))
      throw new Error(`Refusing to replace an unowned JSX declaration: ${file}`);
    if (readFileSync(file, 'utf8') === contents) return;
  }
  const temporary = `${file}.${process.pid}.tmp`;
  try {
    writeFileSync(temporary, contents, { flag: 'wx' });
    renameSync(temporary, file);
  } finally {
    rmSync(temporary, { force: true });
  }
}

/** One saved-source snapshot supplies declarations and direct-call lowering. */
export class FlaxJsxProject {
  constructor(root) {
    this.root = resolve(root);
    this.enabled = jsxEnabled(this.root);
    this.generated = resolve(this.root, 'flax-jsx.generated.d.ts');
    this.dirty = true;
  }
  invalidate() {
    this.dirty = true;
  }
  close() {
    this.current?.close();
    this.current = undefined;
  }
  prepare() {
    if (!this.dirty) return;
    if (this.enabled !== jsxEnabled(this.root))
      throw new Error('JSX switch changed; restart the development command');
    if (!this.enabled) {
      if (
        existsSync(this.generated) &&
        lstatSync(this.generated).isFile() &&
        readFileSync(this.generated, 'utf8').startsWith(marker)
      )
        rmSync(this.generated);
      this.dirty = false;
      return;
    }
    this.close();
    this.current = analyze(this.root, this.generated, (dependencies) => {
      this.dependencies = dependencies;
    });
    this.dependencies = this.current.dependencies;
    this.dirty = false;
  }
  transform(code, filename) {
    this.prepare();
    if (!this.enabled && !/\.[jt]sx$/.test(filename)) return { code };
    if (!this.enabled) {
      // Parse TSX so legacy .tsx files containing only ordinary TypeScript still work.
      const api = new API({
        cwd: this.root,
        fs: { readFile: (file) => (file === filename ? code : undefined) },
      });
      try {
        const snapshot = api.updateSnapshot({ openFiles: [filename] });
        const source = snapshot
          .getDefaultProjectForFile(filename)
          ?.program.getSourceFile(filename);
        let found = false;
        const visit = (node) => {
          if (
            [
              SyntaxKind.JsxElement,
              SyntaxKind.JsxSelfClosingElement,
              SyntaxKind.JsxFragment,
            ].includes(node.kind)
          )
            found = true;
          node.forEachChild(visit);
        };
        source?.forEachChild(visit);
        if (found)
          throw new Error(
            `${filename}: JSX is disabled; set flax.jsx to true in the application package.json`,
          );
      } finally {
        api.close();
      }
      return { code };
    }
    return this.current.transform(code, filename);
  }
}

function formatDiagnostics(program, errors) {
  return errors
    .map((d) => {
      const file = d.fileName ?? 'tsconfig.json';
      const text =
        program.getSourceFile(file)?.text ??
        (existsSync(file) ? readFileSync(file, 'utf8') : '');
      const before = text.slice(0, d.pos ?? 0);
      const line = before.split('\n').length;
      const column = before.length - before.lastIndexOf('\n');
      return `${file}:${line}:${column}: TS${d.code}: ${d.text}`;
    })
    .join('\n');
}

function analyze(root, generated, observeDependencies) {
  if (!existsSync(resolve(root, 'tsconfig.json')))
    throw new Error(`${root}: JSX requires tsconfig.json`);
  publish(generated, existsSync(generated) ? readFileSync(generated, 'utf8') : header);
  let entryText =
    header + 'declare global { namespace JSX { type Element = Widget; } }\n';
  const config = resolve(root, 'flax-jsx.validation.json');
  const configs = new Set([resolve(root, 'tsconfig.json')]);
  const api = new API({
    cwd: root,
    fs: {
      fileExists: (file) => (file === config ? true : undefined),
      readFile: (file) => {
        if (file === generated) return entryText;
        if (file === config)
          return JSON.stringify({
            extends: './tsconfig.json',
            compilerOptions: { skipLibCheck: false },
          });
        if (/\.json$/.test(file)) configs.add(file);
        return undefined;
      },
    },
  });
  try {
    const snapshot = api.updateSnapshot({
      openProjects: [config],
    });
    const project = snapshot.getProject(config);
    const { checker, program } = project;
    // Recovery must also observe a newly imported file that failed validation.
    observeDependencies([...new Set([...program.getSourceFileNames(), ...configs])]);
    const anchor = program.getSourceFile(generated);
    if (!anchor)
      throw new Error(
        `Include flax-jsx.generated.d.ts in tsconfig.json using an optional include glob`,
      );
    const widget = checker.getTypeAtLocation(anchor.statements[1].type);
    const widgets = checker.getTypeAtLocation(anchor.statements[2].type);
    const componentBases = [3, 4].map(
      (index) => checker.getTypeAtLocation(anchor.statements[index].type).id,
    );
    if (!widget || widget.flags & TypeFlags.Any)
      throw new Error('Resolve the public Flax Widget declaration before enabling JSX');
    const models = new Map();
    const tags = new Map();
    const tagErrors = new Map();
    const jsxSources = new Set();
    const moduleRewrites = new Map();
    const syntaxErrors = [
      ...program.getConfigFileParsingDiagnostics(),
      ...program.getSyntacticDiagnostics(),
    ];
    if (syntaxErrors.length) throw new Error(formatDiagnostics(program, syntaxErrors));
    const sources = program
      .getSourceFileNames()
      .filter((file) => {
        const path = relative(root, file);
        return (
          !isAbsolute(path) &&
          path !== '..' &&
          !path.startsWith('..' + sep) &&
          !/\.d\.[cm]?ts$/.test(file)
        );
      })
      .map((file) => program.getSourceFile(file));
    const is = (node, kind) => node?.kind === SyntaxKind[kind];
    const exported = (node) => node.modifiers?.some((m) => is(m, 'ExportKeyword'));
    const modulePath = (file) => {
      let path = relative(root, file)
        .replaceAll('\\', '/')
        .replace(/\.[jt]sx?$/, '.js');
      return path.startsWith('.') ? path : './' + path;
    };
    function fail(source, node, message) {
      const { line, character } = source.getLineAndCharacterOfPosition(
        node.getStart(source),
      );
      throw new Error(
        `${relative(root, source.fileName)}:${line + 1}:${character + 1}: ${message}`,
      );
    }
    function model(type, specifier, name, construct, source, node) {
      const key = `${specifier}#${name}`;
      if (models.has(key)) return models.get(key);
      const signatures = checker.getSignaturesOfType(
        type,
        construct ? SignatureKind.Construct : SignatureKind.Call,
      );
      if (signatures.length !== 1)
        fail(
          source,
          node,
          `JSX requires one unambiguous constructor signature (${signatures.length} found for ${checker.typeToString(type)})`,
        );
      const signature = signatures[0];
      if (signature.typeParameters?.length)
        fail(source, node, 'Generic tags are unsupported JSX; use the original API');
      const ref = `typeof import(${JSON.stringify(specifier)}).${name}`;
      const tuple = `globalThis.${construct ? 'ConstructorParameters' : 'Parameters'}<${ref}>`;
      const parameters = signature.getParameters().map((symbol, index) => {
        const declaration = (
          symbol.valueDeclaration ?? symbol.declarations[0]
        )?.resolve(project);
        if (
          declaration?.dotDotDotToken ||
          (declaration?.name && !is(declaration.name, 'Identifier'))
        )
          fail(
            source,
            node,
            'Rest and destructured parameters are unsupported JSX; use the original API',
          );
        const optionalTag = declaration?.parent?.jsDoc?.some((doc) =>
          doc.tags?.some(
            (tag) =>
              is(tag, 'JSDocParameterTag') &&
              tag.name?.getText() === symbol.name &&
              (tag.isBracketed || is(tag.typeExpression?.type, 'JSDocOptionalType')),
          ),
        );
        return {
          name: symbol.name,
          type: checker.getTypeOfSymbol(symbol),
          required:
            !declaration?.questionToken && !declaration?.initializer && !optionalTag,
          expression: `${tuple}[${index}]`,
        };
      });
      const last = parameters.at(-1);
      const lastType = last && checker.getNonNullableType(last.type);
      const optionParts = lastType?.isIntersectionType() ? lastType.types : [lastType];
      const options =
        last?.name === 'options' &&
        lastType.flags & (TypeFlags.Object | TypeFlags.Intersection) &&
        !checker.getIndexInfosOfType(lastType).length &&
        !checker.getSignaturesOfType(lastType, SignatureKind.Call).length &&
        !checker.getSignaturesOfType(lastType, SignatureKind.Construct).length &&
        !optionParts.some((part) => part?.getSymbol()?.flags & SymbolFlags.Class)
          ? parameters.pop()
          : null;
      const properties = options
        ? checker
            .getPropertiesOfType(checker.getNonNullableType(options.type))
            .map((symbol) => ({
              name: symbol.name,
              type: checker.getTypeOfSymbol(symbol),
              required: !(symbol.flags & SymbolFlags.Optional),
              expression: `globalThis.NonNullable<${options.expression}>[${JSON.stringify(symbol.name)}]`,
            }))
        : [];
      const fields = [...parameters, ...properties];
      if (new Set(fields.map((p) => p.name)).size !== fields.length)
        fail(
          source,
          node,
          'Positional and options fields collide; use the original API',
        );
      const metadata = checker.getPropertyOfType(type, '__flaxJsx');
      const metadataType = metadata && checker.getTypeOfSymbol(metadata);
      const content = metadataType && checker.getPropertyOfType(metadataType, 'slot');
      const override = content && checker.getTypeOfSymbol(content).value;
      const single = fields.find(
        (p) =>
          p.name === (override ?? 'child') &&
          checker.isTypeAssignableTo(widget, p.type),
      );
      const multiple = fields.find(
        (p) => p.name === 'children' && checker.isTypeAssignableTo(widgets, p.type),
      );
      if (override && !(single || (override === 'children' && multiple)))
        fail(source, node, `Invalid content slot override: ${override}`);
      const slot = single ?? multiple;
      const entry = {
        key,
        specifier,
        name,
        ref,
        construct,
        parameters,
        options,
        fields,
        slot,
        many: Boolean(slot && slot === multiple && !single),
      };
      models.set(key, entry);
      return entry;
    }
    // Named exports permit standard declaration merging without changing app classes.
    const classes = new Map();
    const unsupported = new Map();
    for (const source of sources) {
      for (const node of source.statements) {
        if (!is(node, 'ClassDeclaration') || !node.name || !exported(node)) continue;
        if (node.modifiers?.some((m) => is(m, 'DefaultKeyword'))) continue;
        const symbol = checker.getSymbolAtLocation(node.name);
        const instance = checker.getDeclaredTypeOfSymbol(symbol);
        if (!checker.isTypeAssignableTo(instance, widget)) continue;
        if (node.typeParameters?.length) continue;
        const base = node.heritageClauses?.[0]?.types?.[0]?.expression;
        let baseSymbol = base && checker.getSymbolAtLocation(base);
        if (baseSymbol?.flags & SymbolFlags.Alias)
          baseSymbol = checker.getAliasedSymbol(baseSymbol);
        if (
          !baseSymbol ||
          !componentBases.includes(checker.getDeclaredTypeOfSymbol(baseSymbol).id)
        )
          continue;
        let entry;
        try {
          entry = model(
            checker.getTypeOfSymbol(symbol),
            modulePath(source.fileName),
            node.name.text,
            true,
            source,
            node,
          );
          if (
            entry.slot?.name !== 'children' &&
            entry.fields.some((p) => p.name === 'children') &&
            entry.fields.some((p) => p.name === 'child')
          )
            throw new Error('Both child and children require the original API');
          if (node.modifiers?.some((m) => is(m, 'AbstractKeyword')))
            throw new Error('Abstract components cannot be JSX tags');
        } catch (error) {
          if (entry) models.delete(entry.key);
          unsupported.set(symbol.id, error.message);
          continue;
        }
        classes.set(symbol.id, entry);
      }
    }
    for (const source of sources) {
      const imports = new Map();
      for (const node of source.statements) {
        if (!is(node, 'ImportDeclaration')) continue;
        for (const binding of node.importClause?.namedBindings?.elements ?? [])
          imports.set(binding.name.text, {
            specifier: node.moduleSpecifier.text,
            name: (binding.propertyName ?? binding.name).text,
          });
      }
      function visit(node) {
        if (
          is(node, 'StringLiteral') &&
          /^\.\.?\//.test(node.text) &&
          /\.[jt]sx?$/.test(node.text) &&
          (node.parent?.moduleSpecifier === node ||
            (is(node.parent, 'CallExpression') &&
              is(node.parent.expression, 'ImportKeyword')))
        ) {
          if (/\.jsx$|\.tsx?$/.test(node.text))
            moduleRewrites.set(
              `${resolve(source.fileName)}:${node.pos}`,
              JSON.stringify(node.text.replace(/\.[jt]sx?$/, '.js')),
            );
        }
        if (is(node, 'JsxFragment')) jsxSources.add(resolve(source.fileName));
        if (is(node, 'JsxOpeningElement') || is(node, 'JsxSelfClosingElement')) {
          jsxSources.add(resolve(source.fileName));
          if (node.typeArguments?.length)
            fail(
              source,
              node,
              'Generic tags are unsupported JSX; use the original API',
            );
          const tag = node.tagName;
          let symbol = checker.getSymbolAtLocation(tag);
          if (symbol?.flags & SymbolFlags.Alias)
            symbol = checker.getAliasedSymbol(symbol);
          let entry = classes.get(symbol?.id);
          if (!entry) {
            const type = checker.getTypeAtLocation(tag);
            if (!type || !checker.getPropertyOfType(type, '__flaxJsx')) {
              tagErrors.set(
                `${resolve(source.fileName)}:${node.pos}`,
                unsupported.get(symbol?.id) ??
                  'Unsupported JSX tag; use a named exported non-generic component or generated Widget factory',
              );
              node.forEachChild(visit);
              return;
            }
            // The binding's own declaration supplies parameter names and the content policy.
            const signature = checker.getSignaturesOfType(type, SignatureKind.Call)[0];
            const imported = imports.get(tag.getText(source).split('.')[0]);
            if (
              !imported ||
              !signature ||
              !checker.isTypeAssignableTo(
                checker.getReturnTypeOfSignature(signature),
                widget,
              )
            )
              fail(source, tag, 'JSX requires a statically imported Widget factory');
            const suffix = tag.getText(source).split('.').slice(1).join('.');
            entry = model(
              type,
              imported.specifier,
              imported.name + (suffix ? '.' + suffix : ''),
              false,
              source,
              tag,
            );
          }
          tags.set(`${resolve(source.fileName)}:${node.pos}`, entry);
        }
        node.forEachChild(visit);
      }
      visit(source);
    }
    const entries = [...models.values()].filter((e) => e.construct);
    function props(entry) {
      const { slot, many } = entry;
      const ordinary = entry.fields.filter((p) => p !== slot);
      const base = `{ ${ordinary.map((p) => `${JSON.stringify(p.name)}${p.required ? '' : '?'}: ${p.expression}`).join('; ')} }`;
      if (!slot) return base;
      if (slot.name !== 'children' && ordinary.some((p) => p.name === 'children'))
        throw new Error(
          'Both child and children are not expressible unambiguously by this standard JSX contract',
        );
      if (many)
        return `${base} & { children${slot.required ? '' : '?'}: ${slot.expression} | Widget }`;
      const optional = slot.required ? '' : '?';
      return `${base} & ({ ${slot.name}${optional}: ${slot.expression}; children?: never } | { ${slot.name}?: never; children${optional}: ${slot.expression} })`;
    }
    const declarations = entries
      .map((entry, index) => `type Props${index} = ${props(entry)};`)
      .join('\n');
    const augmentations = entries.flatMap((entry, index) =>
      entry.construct
        ? [
            `import type {} from ${JSON.stringify(entry.specifier)};\ndeclare module ${JSON.stringify(entry.specifier)} { interface ${entry.name} { readonly jsxProps: Props${index} } }`,
          ]
        : [],
    );
    const declarationsText = `${header}${declarations}\n${augmentations.join('\n')}\ndeclare global { namespace JSX {
 type Element = Widget;
 type ElementType = ((...args: never[]) => Widget) & { readonly __flaxJsx: { readonly props: unknown } } | (abstract new (...args: never[]) => Widget) & { readonly prototype: { readonly jsxProps: unknown } };
 interface ElementClass { readonly kind: 'component' }
 interface ElementChildrenAttribute { children: {} }
 type LibraryManagedAttributes<C, P> = C extends { readonly __flaxJsx: { readonly props: infer Props } } ? Props : C extends { prototype: { readonly jsxProps: infer Props } } ? Props : never;
} }\n`;
    entryText = declarationsText;
    api.clearSourceFileCache();
    const validation = api
      .updateSnapshot({ fileChanges: { changed: [generated] } })
      .getProject(config);
    function diagnostics(file) {
      return [
        ...validation.program.getSyntacticDiagnostics(file),
        ...validation.program.getSemanticDiagnostics(file),
      ];
    }
    const diagnosticText = (errors) => formatDiagnostics(validation.program, errors);
    const declarationErrors = diagnostics(generated);
    if (declarationErrors.length) throw new Error(diagnosticText(declarationErrors));
    publish(generated, declarationsText);

    function transform(code, filename) {
      const source = sources.find((s) => resolve(s.fileName) === filename);
      if (!source) {
        if (/\.[jt]sx$/.test(filename))
          throw new Error(
            `${filename}: JSX source must belong to the owning tsconfig.json`,
          );
        return { code };
      }
      if (source.text !== code)
        throw new Error(
          `${filename}: Re-run JSX declaration generation after saving source changes`,
        );
      if (
        !jsxSources.has(filename) &&
        ![...moduleRewrites.keys()].some((key) => key.startsWith(filename + ':'))
      )
        return { code };
      const typeErrors = jsxSources.has(filename) ? diagnostics(filename) : [];
      if (typeErrors.length) throw new Error(diagnosticText(typeErrors));
      const names = new Set(code.match(/[$\p{ID_Start}][$\p{ID_Continue}]*/gu) ?? []);
      const scopes = new Map();
      let next = 0;
      function temporary(node, type) {
        let scope = node.parent;
        while (
          scope &&
          !is(scope, 'Block') &&
          !is(scope, 'SourceFile') &&
          !is(scope, 'ArrowFunction')
        ) {
          if (is(scope, 'PropertyDeclaration') || is(scope, 'Parameter'))
            fail(
              source,
              node,
              'Direct JSX field or parameter initializers are unsupported; use a build method or callback',
            );
          scope = scope.parent;
        }
        let name;
        do name = `__flaxJsx${next++}`;
        while (names.has(name));
        names.add(name);
        if (!scopes.has(scope)) scopes.set(scope, []);
        const localType = type.replace(/import\(("[^"]+")\)/g, (match, quoted) => {
          const specifier = JSON.parse(quoted);
          if (!specifier.startsWith('.')) return match;
          let path = relative(dirname(filename), resolve(root, specifier)).replaceAll(
            '\\',
            '/',
          );
          if (!path.startsWith('.')) path = './' + path;
          return `import(${JSON.stringify(path)})`;
        });
        scopes.get(scope).push({ name, type: localType });
        return name;
      }
      const original = new MagicString(code, { filename });
      const slice = (start, end) => original.snip(start, end);
      function render(node) {
        const rewritten = moduleRewrites.get(`${filename}:${node.pos}`);
        if (rewritten) return [rewritten];
        if (is(node, 'JsxFragment'))
          fail(source, node, 'Fragments have no implicit Flutter layout');
        if (is(node, 'JsxElement') || is(node, 'JsxSelfClosingElement'))
          return lower(node);
        const start = is(node, 'SourceFile') ? 0 : node.getStart(source);
        let cursor = start;
        const parts = [];
        let body;
        node.forEachChild((child) => {
          const position = child.getStart(source);
          if (position < cursor || child.end > node.end) return;
          const rendered = render(child);
          if (child === node.body) body = rendered;
          parts.push(slice(cursor, position), ...rendered);
          cursor = child.end;
        });
        parts.push(slice(cursor, node.end));
        const variables = scopes.get(node);
        if (variables?.length) {
          // Contextual types survive attribute reordering without an IIFE or runtime dispatcher.
          const declaration = /\.jsx?$/.test(filename)
            ? variables
                .map((v) => `/** @type {${v.type}} */\nlet ${v.name};\n`)
                .join('')
            : `let ${variables.map((v) => `${v.name}: ${v.type}`).join(', ')};\n`;
          if (is(node, 'ArrowFunction'))
            return [
              slice(start, node.body.getStart(source)),
              '{\n',
              declaration,
              'return ',
              ...body,
              '; }',
            ];
          const first = parts[0];
          const offset = is(node, 'Block') ? 1 : 0;
          parts.splice(
            0,
            1,
            slice(start, start + offset),
            '\n' + declaration,
            slice(start + offset, start + first.length()),
          );
        }
        return parts;
      }
      function lower(node) {
        const opening = node.openingElement ?? node;
        const key = `${filename}:${opening.pos}`;
        if (tagErrors.has(key)) fail(source, opening, tagErrors.get(key));
        const entry = tags.get(key);
        const values = new Map();
        const evaluations = [];
        function singleWidget(value) {
          if (is(value, 'JsxElement') || is(value, 'JsxSelfClosingElement'))
            return true;
          const type = checker.getTypeAtLocation(value);
          if (checker.isTypeAssignableTo(type, entry.slot.type)) return false;
          if (checker.isTypeAssignableTo(type, widget)) return true;
          fail(
            source,
            value,
            'Pass either one Widget or a collection; normalize mixed Widget and collection expressions explicitly',
          );
        }
        function capture(name, expression) {
          if (values.has(name))
            fail(source, node, `Duplicate content or attribute: ${name}`);
          const field = entry.fields.find((p) => p.name === name);
          const variable = temporary(node, field.expression);
          evaluations.push([variable + ' = ', ...expression]);
          values.set(name, variable);
        }
        for (const attribute of opening.attributes.properties) {
          if (is(attribute, 'JsxSpreadAttribute'))
            fail(
              source,
              attribute,
              'Attribute spreads are unsupported JSX; use the original API',
            );
          const attributeName = attribute.name.getText(source);
          const name =
            attributeName === 'children' && entry.slot
              ? entry.slot.name
              : attributeName;
          if (!entry.fields.some((p) => p.name === name))
            fail(source, attribute, `Unknown attribute: ${name}`);
          const value = attribute.initializer;
          if (value && !is(value, 'StringLiteral') && !value.expression)
            fail(source, attribute, 'Empty attribute expression');
          let expression = !value
            ? ['true']
            : is(value, 'StringLiteral')
              ? [
                  JSON.stringify(
                    entities.decode(
                      value.text.replace(/\r\n?/g, '\n').replace(/\n\s*/g, ' '),
                    ),
                  ),
                ]
              : render(value.expression);
          if (
            entry.many &&
            name === entry.slot.name &&
            value?.expression &&
            singleWidget(value.expression)
          )
            expression = ['[', ...expression, ']'];
          capture(name, expression);
        }
        const children = [];
        for (const child of node.children ?? []) {
          if (is(child, 'JsxText')) {
            if (child.text.trim())
              fail(source, child, 'Use an explicit Text Widget for text content');
          } else if (is(child, 'JsxExpression')) {
            if (child.dotDotDotToken)
              fail(
                source,
                child,
                'Spread children are unsupported; pass one Widget array',
              );
            if (child.expression) children.push(child.expression);
          } else children.push(child);
        }
        if (children.length) {
          if (!entry.slot)
            fail(source, node, 'This constructor has no default content slot');
          if (!entry.many && children.length !== 1)
            fail(
              source,
              node,
              'Single content slot received multiple Widgets; use an explicit layout',
            );
          const oneList =
            children.length === 1 && entry.many && !singleWidget(children[0]);
          if (
            entry.many &&
            children.length > 1 &&
            children.some(
              (c) =>
                !is(c, 'JsxElement') &&
                !is(c, 'JsxSelfClosingElement') &&
                checker.isArrayLikeType(checker.getTypeAtLocation(c)),
            )
          )
            fail(
              source,
              node,
              'Use one Widget array or individual Widgets; nested arrays are not flattened',
            );
          capture(
            entry.slot.name,
            entry.many && !oneList
              ? [
                  '[',
                  ...children.flatMap((c, i) => [...(i ? [', '] : []), ...render(c)]),
                  ']',
                ]
              : render(children[0]),
          );
        }
        for (const field of entry.fields)
          if (field.required && !values.has(field.name))
            fail(source, node, `Missing required attribute: ${field.name}`);
        const args = entry.parameters.map((p) => values.get(p.name) ?? 'undefined');
        if (entry.options) {
          const properties = entry.fields.filter(
            (p) => !entry.parameters.includes(p) && values.has(p.name),
          );
          if (properties.length)
            args.push(
              `{ ${properties.map((p) => `${JSON.stringify(p.name)}: ${values.get(p.name)}`).join(', ')} }`,
            );
          else if (entry.options.required) args.push('{}');
        }
        while (args.at(-1) === 'undefined') args.pop();
        const parts = [
          entry.construct ? 'new ' : '',
          slice(opening.tagName.getStart(source), opening.tagName.end),
          '(',
        ];
        // Callee lookup precedes all attribute evaluations, as in an ordinary call.
        if (evaluations.length) {
          parts.push(
            '(',
            ...evaluations.flatMap((e) => [...e, ', ']),
            args[0] ?? 'undefined',
            ')',
          );
          args.shift();
          if (args.length) parts.push(', ');
        }
        parts.push(args.join(', '), ')');
        return parts;
      }
      const bundle = new Bundle({ separator: '' });
      for (const part of render(source))
        bundle.addSource({
          content: typeof part === 'string' ? new MagicString(part) : part,
        });
      return {
        code: bundle.toString(),
        map: bundle.generateMap({ file: filename, includeContent: true, hires: true }),
      };
    }
    return {
      enabled: true,
      generated,
      models: entries,
      dependencies: [...new Set([...program.getSourceFileNames(), ...configs])],
      transform,
      close: () => api.close(),
    };
  } catch (error) {
    api.close();
    throw error;
  }
}
