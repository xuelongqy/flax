const key = (name) => `[${JSON.stringify(name)}]`;
const object = (entries) =>
  `{${entries.map(([name, value]) => `${key(name)}: ${value}`).join(', ')}}`;

/** Emit against the existing runtime API; the model is a private compiler intermediate. */
export function emit(model, { resources = {}, compatibility = 'flax' } = {}) {
  const names = new Map(
    model.layouts.map((record, index) => [record.name, `_layout${index}`]),
  );
  const type = (value) => {
    if (typeof value === 'string') {
      if (compatibility === 'node' && value === 'c_bool')
        throw new Error(
          'C boolean semantics require Flax c_bool; use a C uint8 wrapper for Node',
        );
      return JSON.stringify(value);
    }
    if (compatibility === 'node')
      throw new Error('Node-compatible definitions cannot contain aggregates');
    if (value.kind === 'record') return names.get(value.name);
    return `array(${type(value.element)}, ${value.length})`;
  };
  const signature = (value) => {
    if (compatibility === 'node' && value.fixedArguments !== undefined)
      throw new Error(
        'Node-compatible definitions cannot contain explicit variadic bindings',
      );
    return `{arguments: [${value.arguments.map(type).join(', ')}], return: ${type(value.return)}${value.fixedArguments === undefined ? '' : `, fixedArguments: ${value.fixedArguments}`}}`;
  };
  const constants = Object.entries(model.constants).map(([name, text]) => {
    const value = BigInt(text);
    const literal =
      value <= BigInt(Number.MAX_SAFE_INTEGER) &&
      value >= BigInt(Number.MIN_SAFE_INTEGER)
        ? `${value}`
        : `${value}n`;
    return [name, literal];
  });
  const definitions =
    [
      '// Generated by @flax/ffi-codegen. Do not edit.',
      ...(model.layouts.length
        ? ["import {struct, union, array} from '@flax/ffi';"]
        : []),
      ...model.layouts.map(
        (record) =>
          `const ${names.get(record.name)} = ${record.kind}(${object(record.fields.map((field) => [field.name, type(field.type)]))}${record.pack ? `, {pack: ${record.pack}}` : ''});`,
      ),
      `export const layouts = ${object(model.layouts.flatMap((record) => [...new Set([record.name, ...(record.aliases ?? [])])].map((alias) => [alias, names.get(record.name)])))};`,
      `export const constants = ${object(constants)} as const;`,
      `export const callbacks = ${object(Object.entries(model.callbacks).map(([name, sig]) => [name, signature(sig)]))} as const;`,
      `export const globals = ${object(Object.entries(model.globals).map(([name, value]) => [name, type(value)]))} as const;`,
      `export const definitions = ${object(Object.entries(model.definitions).map(([name, sig]) => [name, signature(sig)]))} as const;`,
    ].join('\n') + '\n';
  const resourceCode = [],
    resourceExports = [];
  for (const [name, config] of Object.entries(resources)) {
    const create = model.definitions[config.create],
      destroy = model.definitions[config.destroy];
    if (!create || create.return !== 'pointer')
      throw new Error(`${name}: constructor must return a pointer`);
    if (
      !destroy ||
      destroy.fixedArguments !== undefined ||
      destroy.return !== 'void' ||
      JSON.stringify(destroy.arguments) !== '["pointer"]'
    )
      throw new Error(
        `${name}: GC destructor must be void(pointer); use a native cleanup wrapper`,
      );
    const index = resourceExports.length,
      cls = `_Resource${index}`,
      finalizer = `_finalizer${index}`,
      cleanup = `_cleanup${index}`;
    const get = (symbol) => `native[${JSON.stringify(symbol)}]`;
    const methods = [];
    for (const [method, rule] of Object.entries(config.methods ?? {})) {
      if (['constructor', 'close'].includes(method))
        throw new Error(`${name}: reserved method ${method}`);
      const { symbol, receiver = 0 } =
        typeof rule === 'string' ? { symbol: rule } : rule;
      if (symbol === config.destroy)
        throw new Error(`${name}.${method}: use close() for the configured destructor`);
      const sig = model.definitions[symbol];
      if (
        !sig ||
        !Number.isInteger(receiver) ||
        receiver < 0 ||
        sig.arguments[receiver] !== 'pointer'
      )
        throw new Error(`${name}.${method}: receiver must select a pointer argument`);
      const args = sig.arguments
        .map((_, i) => (i === receiver ? null : i))
        .filter((i) => i !== null);
      methods.push(`${key(method)}(${args.map((i) => `arg${i}: Parameters<typeof ${get(symbol)}>[${i}]`).join(', ')}) {
        if (this.#pointer === 0n) throw new Error('Resource closed');
        // Keep the receiver alive and reject close from reentrant native callbacks.
        ++this.#active;
        try { return ${get(symbol)}(${sig.arguments.map((_, i) => (i === receiver ? 'this.#pointer' : `arg${i}`)).join(', ')}); }
        finally { --this.#active; }
      }`);
    }
    resourceCode.push(`const ${cleanup} = ${get(config.destroy)};
    const ${finalizer} = new NativeFinalizer(${cleanup});
    class ${cls} {
      #pointer: bigint;
      #detach = {};
      #active = 0;
      constructor(...args: Parameters<typeof ${get(config.create)}>) {
        const pointer = ${get(config.create)}(...args);
        if (pointer === 0n) throw new Error('Native allocation failed');
        try { ${finalizer}.attach(this, pointer, {detach: this.#detach}); }
        catch (error) {
          try { ${cleanup}(pointer); }
          catch (cleanup) { throw new AggregateError([error, cleanup], 'Constructor cleanup failed', {cause: error}); }
          throw error;
        }
        this.#pointer = pointer;
      }
      ${methods.join('\n')}
      close() {
        if (this.#pointer === 0n) return;
        if (this.#active !== 0) throw new Error('Resource is in use');
        // Keep GC ownership if a closed library cannot run manual cleanup.
        void library.handle;
        ${finalizer}.detach(this.#detach);
        const pointer = this.#pointer;
        this.#pointer = 0n;
        ${cleanup}(pointer);
      }
    }`);
    resourceExports.push([name, cls]);
  }
  const checks = model.layouts.flatMap((record) => {
    const name = `layouts[${JSON.stringify(record.name)}]`;
    return [
      `check(sizeOf(${name}) === ${record.size} && alignOf(${name}) === ${record.alignment}, ${JSON.stringify(`${record.name} size/alignment`)});`,
      ...record.fields.map(
        (field) =>
          `check(offsetOf(${name}, ${JSON.stringify(field.name)}) === ${field.offset}, ${JSON.stringify(`${record.name}.${field.name} offset`)});`,
      ),
    ];
  });
  const bindings =
    [
      '// Generated by @flax/ffi-codegen. Do not edit.',
      ...(resourceCode.length ? ["import {NativeFinalizer} from '@flax/ffi';"] : []),
      ...(checks.length
        ? [
            "import {sizeOf, alignOf, offsetOf} from '@flax/ffi';",
            "import {layouts} from './definitions.g.js';",
            'function check(value: boolean, message: string) { if (!value) throw new Error(message); }',
          ]
        : []),
      "import type {DynamicLibrary} from '@flax/ffi';",
      "import {definitions} from './definitions.g.js';",
      'export function createBindings(library: DynamicLibrary) {',
      ...checks,
      'const native = library.getFunctions(definitions);',
      ...resourceCode,
      `return {native${resourceExports.length ? ', ' + resourceExports.map(([name, cls]) => `${key(name)}: ${cls}`).join(', ') : ''}};`,
      '}',
    ].join('\n') + '\n';
  if (compatibility === 'node' && resourceCode.length)
    throw new Error(
      'Node-compatible definitions cannot contain NativeFinalizer resources',
    );
  return {
    'definitions.g.ts': definitions,
    ...(compatibility === 'node' ? {} : { 'bindings.g.ts': bindings }),
  };
}
