#!/usr/bin/env python3
"""Generate the private Dawn ABI and descriptor metadata from the locked SDK/IDL."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
sys.dont_write_bytecode = True
from public_types import generate as generate_public_types, blocks

ROOT = Path(__file__).resolve().parents[3]
PACKAGE = Path(__file__).resolve().parents[1]
REVISION = '5fbd545292cb7a4a9a275e322abec6007ffe2ae8'
IDL_REVISION = '22507c95ccb9e705eddc7cab8f28aa46b134f5fe'
CTS_REVISION = 'cc11994e92512d0a3715e9d28876ec48accb971a'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sdk', type=Path, required=True)
    args = parser.parse_args()
    sdk = args.sdk.resolve()
    header = (sdk / 'include/dawn/webgpu.h').read_text()
    version = (sdk / 'include/dawn/dawn_version.h').read_text()
    revision = ''.join(re.findall(r'0x([0-9a-fA-F]{2})', re.search(r'kDawnVersion = \{([^}]+)', version)[1]))
    if revision != REVISION or hashlib.sha256(header.encode()).hexdigest() != '44126360bbd35339b3b1ccb8ab5bdf21a4a1109bc05f086b179df5ea5a2734d0':
        raise RuntimeError('This generator requires the locked Dawn SDK; update the pins explicitly before upgrading')
    idl_path = PACKAGE / 'native/generated/webgpu.idl'
    if hashlib.sha256(idl_path.read_bytes()).hexdigest() != '5293ea7f38416cb37b0ddfc636286514ff622901caa19504a4bdede2ec5a80b2':
        raise RuntimeError('The vendored WebGPU IDL does not match its pin')
    idl = re.sub(r'//[^\n]*', '', idl_path.read_text())
    structs = {}
    for name, body in re.findall(r'typedef struct (WGPU\w+)\s*\{(.*?)\}\s*\1', header, re.S):
        fields = {}
        for declaration in body.split(';'):
            declaration = re.sub(r'/\*.*?\*/|//[^\n]*|WGPU_NULLABLE', '', declaration, flags=re.S).strip()
            if not declaration:
                continue
            match = re.fullmatch(r'(.+?)\s+(\w+)', declaration)
            if not match:
                raise ValueError(f'Unrecognized field in {name}: {declaration}')
            fields[match[2]] = match[1].strip()
        structs[name] = fields
    assert len(structs) > 100
    dictionaries = {}
    for name, parent, body in blocks(idl, r'dictionary (\w+)\s*(?::\s*(\w+))?'):
        fields = {}
        for declaration in body.split(';'):
            declaration = declaration.strip()
            if not declaration: continue
            required = declaration.startswith('required ')
            declaration = re.sub(r'^required\s+', '', declaration)
            parts = declaration.split('=', 1)
            field = re.fullmatch(r'(.+?)\s+(\w+)', parts[0].strip(), re.S)
            assert field, declaration
            fields[field[2]] = {'type': ' '.join(field[1].split()), 'required': required}
            if len(parts) == 2:
                default = parts[1].strip()
                fields[field[2]]['default'] = int(default, 16) if default.startswith('0x') else json.loads(default)
        dictionaries[name] = {'parent': parent or None, 'fields': fields}
    enums = {name: re.findall(r'"([^"]*)"', body)
             for name, body in re.findall(r'enum (\w+)\s*\{(.*?)\}', idl, re.S)}
    aliases = dict((name, value.strip()) for value, name in re.findall(r'typedef\s+([^;]+?)\s+(\w+)\s*;', idl))
    objects = re.findall(r'typedef struct WGPU\w+Impl\s*\*\s*(WGPU\w+)\b', header)
    assert len(objects) > 20
    metadata = {'structs': structs, 'objects': objects, 'dictionaries': dictionaries, 'enums': enums, 'aliases': aliases}
    generate_public_types(idl, metadata, PACKAGE / 'js/src')
    output = PACKAGE / 'js/src/generated'
    output.mkdir(parents=True, exist_ok=True)
    (output / 'metadata.ts').unlink(missing_ok=True)
    generated = PACKAGE / 'native/generated'
    native_features = re.findall(r'WGPUFeatureName_(\w+)\s*=', header)
    normalize = lambda name: re.sub(r'[^a-z0-9]', '', name.lower())
    features = []
    for name in enums['GPUFeatureName']:
        matches = [n for n in native_features if normalize(n) == normalize(name)]
        assert len(matches) == 1, name
        features.append(f'{{"{name}", wgpu::FeatureName::{matches[0]}}},\n')
    (generated / 'feature_names.inc').write_text('// Generated by tool/generate.py.\n' + ''.join(features))
    wgsl = []
    for name, value in re.findall(r'WGPUWGSLLanguageFeatureName_(\w+)\s*=\s*(0x[0-9a-fA-F]+)', header):
        if int(value,16) >= 0x50000: continue
        public = re.sub(r'(?<=[a-z0-9])(?=[A-Z])', '_', name).lower().replace('packed4x8','packed_4x8')
        wgsl.append(f'WGSL_FEATURE({name}, "{public}")\n')
    (generated / 'wgsl_features.inc').write_text('// Generated by tool/generate.py.\n' + ''.join(wgsl))
    limits = re.search(r'interface GPUSupportedLimits\s*\{(.*?)\}', idl, re.S)[1]
    lines = []
    for name in re.findall(r'attribute\s+(?:unsigned long(?: long)?)\s+(\w+)', limits):
        common = re.sub(r'In(?:Vertex|Fragment)Stage$', 'PerShaderStage', name)
        lines.append(f'LIMIT({name})\n' if name == common else f'STAGE_LIMIT({name}, {common})\n')
    (generated / 'limits.inc').write_text('// Generated by tool/generate.py.\n' + ''.join(lines))
    defaults = []
    for macro, name in re.findall(r'#define (WGPU_\w+_INIT) _wgpu_MAKE_INIT_STRUCT\((WGPU\w+),', header):
        if name not in structs:
            continue
        defaults.append(f'if (!strcmp(name, "{name}")) {{ if (size != sizeof({name})) throw std::invalid_argument("WebGPU structure size mismatch"); {name} value = {macro}; memcpy(data, &value, size); return; }}\n')
    assert len(defaults) > 100
    (generated / 'struct_defaults.inc').write_text('// Generated by tool/generate.py.\n' + ''.join(defaults))
    config = {'cwd': str(PACKAGE), 'headers': [str(PACKAGE / 'native/include/flax/webgpu.h')],
              'includes': [str(sdk / 'include')], 'output': str(output),
              'functions': ['wgpu*', 'flax_webgpu_*'], 'records': list(structs), 'enums': ['WGPU*'],
              'language': 'c++', 'std': 'c++20', 'compatibility': 'flax',
              'target': 'macos-arm64', 'deploymentTarget': '26.0',
              'cacheDirectory': str(ROOT / '.local/webgpu-dawn/codegen-cache')}
    command = "import {generateBindings} from './packages/flax_ffi_codegen/js/src/index.mjs'; import {readFileSync} from 'node:fs'; await generateBindings(JSON.parse(readFileSync(0,'utf8')));"
    subprocess.run(['node', '--input-type=module', '-e', command], input=json.dumps(config),
                   text=True, cwd=ROOT, check=True)
    (output.parent / 'metadata.g.ts').write_text('// Generated by tool/generate.py. Do not edit.\nexport default ' + json.dumps(metadata) + ';\n')
    (generated / 'inputs.json').write_text(json.dumps({'dawnRevision': REVISION, 'gpuwebRevision': IDL_REVISION,
        'ctsRevision': CTS_REVISION,
        'headerSha256': hashlib.sha256(header.encode()).hexdigest(),
        'idlSha256': hashlib.sha256(idl_path.read_bytes()).hexdigest()}, indent=2) + '\n')
    print(f'Generated {len(structs)} native structures and {len(dictionaries)} WebGPU dictionaries')


if __name__ == '__main__':
    main()
