"""Emit the implemented native-host profile from the locked WebGPU IDL."""
import re
import json

def blocks(source, pattern):
    for match in re.finditer(pattern + r'\s*\{', source, re.S):
        start, depth, quoted, escaped = match.end(), 1, False, False
        for end in range(start, len(source)):
            char = source[end]
            if escaped: escaped = False; continue
            if quoted and char == '\\': escaped = True; continue
            if char == '"': quoted = not quoted
            if quoted: continue
            if char == '{': depth += 1
            if char == '}': depth -= 1
            if depth == 0:
                yield (*match.groups(), source[start:end]); break
        else: raise ValueError('Unclosed WebIDL block')

