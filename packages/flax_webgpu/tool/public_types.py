def split(value, separator=','):
    depth, start, parts = 0, 0, []
    for i, char in enumerate(value):
        if char in '<(': depth += 1
        elif char in '>)': depth -= 1
        elif char == separator and depth == 0:
            parts.append(value[start:i].strip()); start = i + 1
    parts.append(value[start:].strip())
    return parts


def generate(idl, metadata, output):
    def ts(value):
        value = ' '.join(re.sub(r'\[[^\]]*\]\s*', '', value).split())
        if value.endswith('?'): return ts(value[:-1]) + ' | null'
        if value.startswith('(') and value.endswith(')'):
            return ' | '.join('undefined' if item == 'undefined' else ts(item) for item in value[1:-1].split(' or '))
        for prefix, target in [('sequence<', 'Iterable'), ('FrozenArray<', 'ReadonlyArray'), ('record<','Record'), ('Promise<','Promise')]:
            if value.startswith(prefix):
                return target + '<' + ', '.join(ts(item) for item in split(value[len(prefix):-1])) + '>'
        if value in ['DOMString','USVString']: return 'string'
        if value in ['byte','octet','short','unsigned short','long','unsigned long','long long','unsigned long long','double','unrestricted double','float','unrestricted float']: return 'number'
        return {'undefined':'void','EventHandler':'((event: GPUUncapturedErrorEvent) => unknown) | null',
                'AllowSharedBufferSource':'ArrayBuffer | SharedArrayBuffer | ArrayBufferView',
                'HTMLVideoElement':'never','VideoFrame':'never','GPUExternalTexture':'never',
                'GPUExternalTextureDescriptor':'never',
                'PredefinedColorSpace':'"srgb" | "display-p3"'}.get(value,value)
    lines = ['// Generated by tool/generate.py from pinned WebGPU IDL. Do not edit.',
             "import type {OffscreenCanvas, HTMLCanvasElement, HTMLImageElement, ImageData, ImageBitmap, Event, EventInit, EventTarget, DOMException} from '@flax/core/host/common';"]
    for name, values in metadata['enums'].items():
        lines.append('export type ' + name + ' = ' + ' | '.join(repr(v) for v in values) + ';')
    for name, value in metadata['aliases'].items():
        lines.append(f'export type {name} = {ts(value)};')
    for name, spec in metadata['dictionaries'].items():
        parent = ' extends ' + spec['parent'] if spec['parent'] else ''
        lines.append(f'export interface {name}{parent} {{')
        for field, value in spec['fields'].items():
            lines.append(f'  {field}{"" if value["required"] else "?"}: {ts(value["type"])};')
        lines.append('}')
    bodies, parents = {}, {}
    for name, parent, body in blocks(idl, r'(?:partial\s+)?interface(?:\s+mixin)?\s+(\w+)\s*(?::\s*(\w+))?'):
        bodies[name] = bodies.get(name,'') + body
        if parent: parents[name] = parent
    includes = {}
    for target, mixin in re.findall(r'(\w+) includes (\w+);', idl): includes.setdefault(target,[]).append(mixin)
    arities = {}
    for name, allowed in METHODS.items():
        assert name in bodies, name
        parent = parents.get(name)
        if name in ['GPUSupportedFeatures','WGSLLanguageFeatures']: parent = 'ReadonlySet<string>'
        lines.append(f'export interface {name}' + (f' extends {parent}' if parent else '') + ' {')
        body = bodies[name] + ''.join(bodies[mixin] for mixin in includes.get(name,[]))
        found = set()
        for declaration in re.sub(r'\[[^\]]*\]', '', body).split(';'):
            declaration = declaration.strip()
            attr = re.fullmatch(r'(readonly\s+)?attribute\s+(.+?)\s+(\w+)', declaration, re.S)
            if attr:
                lines.append(f'  {"readonly " if attr[1] else ""}{attr[3]}: {ts(attr[2])};')
                continue
            match = re.fullmatch(r'(.+?)\s+(\w+)\((.*)\)', declaration, re.S)
            if not match or match[2] not in allowed.split(): continue
            args = []
            required = 0
            for argument in split(match[3]):
                if not argument: continue
                argument = argument.split('=')[0].strip()
                optional = argument.startswith('optional ')
                if not optional: required += 1
                argument = re.sub(r'^optional\s+', '', argument)
                arg = re.fullmatch(r'(.+?)\s+(\w+)', argument, re.S)
                assert arg, argument
                args.append(f'{arg[2]}{"?" if optional else ""}: {ts(arg[1])}')
            # Keep the allocation-free frontend's six argument slots in sync.
            assert len(args) <= 6, (name, match[2], len(args))
            lines.append(f'  {match[2]}({", ".join(args)}): {ts(match[1])};')
            found.add(match[2])
            methods = arities.setdefault(name, {})
            methods[match[2]] = min(methods.get(match[2], required), required)
        assert found == set(allowed.split()), (name, found, allowed)
        lines.append('}')
    for name, body in re.findall(r'namespace (GPU\w+)\s*\{(.*?)\}\s*;', idl, re.S):
        values = re.findall(r'const\s+\w+\s+(\w+)\s*=\s*(0x[\da-fA-F]+|\d+)', body)
        lines.append(f'export declare const {name}: {{' + ''.join(f'readonly {key}: {int(value,0)};' for key,value in values) + '};')
    (output / 'types.g.ts').write_text('\n'.join(lines) + '\n')
    (output / 'arity.g.ts').write_text('// Generated by tool/generate.py. Do not edit.\nexport default ' + json.dumps(arities) + ';\n')
    globals = ["import type * as WebGPU from './types.g.js';", "import type { OffscreenCanvasConstructor } from '@flax/core/host/common';", 'declare global {',
               '  var OffscreenCanvas: OffscreenCanvasConstructor;',
               '  function requestAnimationFrame(callback: (time: number) => void): number;',
               '  function cancelAnimationFrame(id?: number): void;']
    for name in METHODS:
        globals.append(f'  type {name} = WebGPU.{name};')
        ctor = 'new(message: string): WebGPU.' + name + ';' if name in ['GPUValidationError','GPUOutOfMemoryError','GPUInternalError'] else ''
        if name == 'GPUUncapturedErrorEvent': ctor = 'new(type: string, init: WebGPU.GPUUncapturedErrorEventInit): WebGPU.GPUUncapturedErrorEvent;'
        if name == 'GPUPipelineError': ctor = 'new(message: string, init: WebGPU.GPUPipelineErrorInit): WebGPU.GPUPipelineError;'
        globals.append(f'  var {name}: {{{ctor} readonly prototype: WebGPU.{name}}};')
    for name in re.findall(r'namespace (GPU\w+)\s*\{', idl): globals.append(f'  var {name}: typeof WebGPU.{name};')
    globals += ['}', "declare module '@flax/core/host/canvas-contexts' {", '  interface CanvasContextMap {webgpu: WebGPU.GPUCanvasContext}',
                '}', "declare module '@flax/core/host/common' {", '  interface Navigator {readonly gpu: WebGPU.GPU}', '}', 'export {};']
    (output / 'globals.ts').write_text('// Generated by tool/generate.py. Do not edit.\n' + '\n'.join(globals) + '\n')
