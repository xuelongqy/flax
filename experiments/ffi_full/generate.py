#!/usr/bin/env python3
"""Generate the fixture provider table from selected, checked C declarations."""
import argparse
import json
from pathlib import Path
import subprocess


def generate(root, spec):
    experiment = Path(__file__).resolve().parent
    expected = {"create": "owned:counter", "update": "borrowed:counter", "destroy": "release:counter"}
    if spec.get("ownership") != expected:
        raise ValueError("The fixture requires explicit counter ownership and release annotations")
    ast = json.loads(subprocess.check_output(["clang", "-x", "c", "-std=c17", "-Xclang",
        "-ast-dump=json", "-fsyntax-only", "-I" + str(root / "packages/flax/native/include"),
        str(experiment / "native/provider_api.h")], text=True))
    declarations = {node["name"]: node["type"]["qualType"] for node in ast["inner"]
                    if node.get("kind") == "FunctionDecl"}
    fields = []
    for field, (symbol, signature) in spec["entries"].items():
        if declarations.get(symbol) != signature:
            raise ValueError(f"C signature mismatch for {symbol}: {declarations.get(symbol)}")
        fields.append(f"  .{field} = {symbol},")
    return ('/* Generated by generate.py. Fixture ABI only. */\n'
            'static const FfiProvider provider = {\n  .version = 1, .size = sizeof(FfiProvider),\n' +
            "\n".join(fields) + '\n};\n'
            'const FfiProvider* flax_ffi_fixture_provider(void) { return &provider; }\n')


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    directory = Path(__file__).resolve().parent
    root = directory.parents[1]
    spec = json.loads((directory / "provider.json").read_text())
    result = generate(root, spec)
    # Negative self-check: missing lifetime metadata must never be inferred from C.
    try:
        generate(root, {**spec, "ownership": {}})
    except ValueError:
        pass
    else:
        raise AssertionError("Missing ownership annotations were accepted")
    changed = json.loads(json.dumps(spec))
    changed["entries"]["add"][1] = "void (void)"
    try:
        generate(root, changed)
    except ValueError:
        pass
    else:
        raise AssertionError("An incompatible C declaration was accepted")
    output = directory / "native/provider.g.inc"
    if options.check:
        if output.read_text() != result: raise SystemExit("Generated provider is stale")
    else:
        output.write_text(result)
    print("Provider declarations, ownership rejection and generated table: passed")
