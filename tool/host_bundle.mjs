import { buildHost, buildNotices, hostBundles, root } from './src/host_bundle.mjs';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, relative } from 'node:path';

const arguments_ = process.argv.slice(2);
const check = arguments_.includes('--check');
const packageIndex = arguments_.indexOf('--package');
const selectedPackage = packageIndex < 0 ? undefined : arguments_[packageIndex + 1];
const consumed = new Set([...(check ? ['--check'] : [])]);
if (packageIndex >= 0) {
  if (!selectedPackage) throw new Error('Missing value for --package');
  consumed.add('--package');
  consumed.add(selectedPackage);
}
if (arguments_.some((argument) => !consumed.has(argument)))
  throw new Error(
    'Usage: node tool/host_bundle.mjs [--check] [--package <dart-package>]',
  );

async function update(path, content, label) {
  if (check) {
    if ((await readFile(path, 'utf8')) !== content)
      throw new Error(`Stale ${label}: ${relative(root, path)}`);
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
  }
}

const selectedBundles = selectedPackage
  ? hostBundles.filter((bundle) => bundle.packageName === selectedPackage)
  : hostBundles;
if (selectedPackage && selectedBundles.length === 0)
  throw new Error(`Package has no host bundle: ${selectedPackage}`);

for (const bundle of selectedBundles) {
  const script = await buildHost(bundle);
  const content = `// Generated by tool/host_bundle.mjs. Do not edit.\n// Embedded dependencies retain their upstream notices below.\n// dart format off\nconst ${bundle.symbol} = ${JSON.stringify(script).replaceAll('$', '\\$')};\n`;
  await update(bundle.output, content, 'host bundle');
  await update(bundle.noticesOutput, await buildNotices(bundle), 'notices');
  console.log(
    `${check ? 'Checked' : 'Generated'} ${relative(root, bundle.output)}: ${Buffer.byteLength(script)} JS bytes`,
  );
}
