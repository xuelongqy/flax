import { readFile, readdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, relative } from 'node:path';
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

export const root = fileURLToPath(new URL('../../', import.meta.url));

export async function discoverHostBundles() {
  const packageRoot = join(root, 'packages');
  const bundles = [];
  for (const entry of await readdir(packageRoot, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const directory = join(packageRoot, entry.name);
    const configPath = join(directory, 'js', 'host.json');
    let config;
    try {
      config = JSON.parse(await readFile(configPath, 'utf8'));
    } catch (error) {
      if (error?.code === 'ENOENT') continue;
      throw error;
    }
    for (const field of ['bridge', 'symbol', 'notices']) {
      if (config[field] === undefined)
        throw new Error(`Missing ${field} in ${relative(root, configPath)}`);
    }
    bundles.push({
      packageName: entry.name,
      packageRoot: directory,
      entry: join(directory, 'js', 'src', 'host', 'bootstrap.ts'),
      output: join(directory, 'lib', 'src', 'generated', 'host_bootstrap.g.dart'),
      noticesOutput: join(directory, 'THIRD_PARTY_NOTICES.txt'),
      base: config.base === true,
      bridge: config.bridge,
      symbol: config.symbol,
      notices: config.notices,
    });
  }
  bundles.sort((left, right) => left.packageName.localeCompare(right.packageName));
  const bases = bundles.filter((bundle) => bundle.base);
  if (bases.length !== 1) throw new Error('Exactly one base host bundle is required');
  const baseSource = join(bases[0].packageRoot, 'js', 'src', 'host');
  return bundles.map((bundle) => ({ ...bundle, baseSource }));
}

export const hostBundles = await discoverHostBundles();

export async function buildHost(bundle) {
  if (bundle.base) {
    const require = createRequire(join(bundle.packageRoot, 'js', 'package.json'));
    const { version } = JSON.parse(
      await readFile(require.resolve('web-streams-polyfill/package.json'), 'utf8'),
    );
    if (version !== '4.3.0')
      throw new Error(
        `Fetch Streams adapter requires web-streams-polyfill 4.3.0, found ${version}`,
      );
  }
  const result = await build({
    absWorkingDir: root,
    entryPoints: [bundle.entry],
    bundle: true,
    write: false,
    platform: 'neutral',
    conditions: ['react-native'],
    mainFields: ['module', 'main'],
    format: 'iife',
    globalName: 'FlaxBootstrap',
    target: 'es2019',
    supported: { 'async-generator': false, 'for-await': false },
    minify: true,
    legalComments: 'inline',
    metafile: true,
  });
  const baseSource = relative(root, bundle.baseSource);
  for (const name of Object.keys(result.metafile.inputs)) {
    if (name.startsWith('node:'))
      throw new Error(`Node builtin in host bundle: ${name}`);
    if (
      !bundle.base &&
      (name.includes('web-streams-polyfill') || name.startsWith(baseSource))
    ) {
      throw new Error(`Duplicate base implementation in plugin: ${name}`);
    }
  }
  return `(() => {${result.outputFiles[0].text}\nreturn FlaxBootstrap.install(globalThis, ${bundle.bridge});})()`;
}

export async function buildNotices(bundle) {
  let content = 'Generated by tool/host_bundle.mjs. Upstream dependency licenses.\n';
  const require = createRequire(join(bundle.packageRoot, 'js', 'package.json'));
  for (const dependency of bundle.notices) {
    let directory = dirname(require.resolve(dependency));
    let manifestPath;
    let manifest;
    while (true) {
      const candidate = join(directory, 'package.json');
      try {
        const value = JSON.parse(await readFile(candidate, 'utf8'));
        if (value.name === dependency) {
          manifestPath = candidate;
          manifest = value;
          break;
        }
      } catch (error) {
        if (error?.code !== 'ENOENT') throw error;
      }
      const parent = dirname(directory);
      if (parent === directory)
        throw new Error(`Cannot locate package manifest for ${dependency}`);
      directory = parent;
    }
    content += `\n${manifest.name} ${manifest.version}\n\n${await readFile(
      join(dirname(manifestPath), 'LICENSE'),
      'utf8',
    )}\n`;
  }
  return content;
}
